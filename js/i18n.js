const I18N = { en: EN, de: {} };

// Deutsche Originaltexte aus dem HTML merken
document.querySelectorAll("[data-i18n]").forEach((el) => {
  I18N.de[el.dataset.i18n] = el.textContent;
});
// Deutsche Bildbeschreibungen merken
document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
  I18N.de[el.dataset.i18nAlt] = el.getAttribute("alt");
});
Object.assign(I18N.de, {
  "hours.today": "Heute",
  "map.title": "Standort Slay Nails by Harmony",
  "aria.menuOpen": "Menü öffnen", "aria.menuClose": "Menü schließen",
  "aria.gallery": "Galerie", "aria.close": "Schließen", "aria.prev": "Zurück", "aria.next": "Weiter",
  "meta.title": document.title,
  "meta.description": document.querySelector('meta[name="description"]').content
});

let currentLang = "de";
const t = (key) => (I18N[currentLang] && I18N[currentLang][key]) ?? I18N.de[key] ?? key;

function setLang(lang) {
  currentLang = lang === "en" ? "en" : "de";
  document.documentElement.lang = currentLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    el.setAttribute("alt", t(el.dataset.i18nAlt));
  });

  // Buchungsseite in der passenden Sprache öffnen
  document.querySelectorAll(".js-book").forEach((a) => {
    a.href = a.href.replace(/locale=\w+/, "locale=" + currentLang);
  });

  document.querySelectorAll(".lang__btn").forEach((btn) => {
    const active = btn.dataset.lang === currentLang;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", active);
  });

  document.title = t("meta.title");
  document.querySelector('meta[name="description"]').content = t("meta.description");
  document.querySelectorAll("#hours td:first-child").forEach((td) => (td.dataset.today = t("hours.today")));

  const iframe = document.querySelector("#map iframe");
  if (iframe) iframe.title = t("map.title");

  const navToggle = document.getElementById("navToggle");
  const open = navToggle.getAttribute("aria-expanded") === "true";
  navToggle.setAttribute("aria-label", t(open ? "aria.menuClose" : "aria.menuOpen"));

  // Beschriftungen der Galerie-Vergrößerung
  const lb = document.getElementById("lightbox");
  if (lb) {
    lb.setAttribute("aria-label", t("aria.gallery"));
    document.getElementById("lbClose").setAttribute("aria-label", t("aria.close"));
    document.getElementById("lbPrev").setAttribute("aria-label", t("aria.prev"));
    document.getElementById("lbNext").setAttribute("aria-label", t("aria.next"));
  }

  try { localStorage.setItem("lang", currentLang); } catch (e) {}
}

// Beim Umschalten: Inhalt kurz ausblenden, Texte tauschen, wieder einblenden
let langTimer;
document.querySelectorAll(".lang__btn").forEach((btn) =>
  btn.addEventListener("click", () => {
    if (btn.dataset.lang === currentLang) return;
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return setLang(btn.dataset.lang);
    clearTimeout(langTimer);
    document.body.classList.add("is-switching");
    langTimer = setTimeout(() => {
      setLang(btn.dataset.lang);
      requestAnimationFrame(() => document.body.classList.remove("is-switching"));
    }, 180);
  })
);

// Startsprache: gespeicherte Wahl, sonst Browsersprache
let startLang = "de";
try { startLang = localStorage.getItem("lang"); } catch (e) {}
if (!startLang) startLang = (navigator.language || "de").toLowerCase().startsWith("de") ? "de" : "en";
setLang(startLang);
